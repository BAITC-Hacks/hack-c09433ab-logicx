/**
 * Smart Builder.
 *
 * Принимает сырое описание задачи и возвращает:
 * - уточняющие вопросы;
 * - предварительно извлечённые поля карточки.
 *
 * AI не придумывает факты, которых нет в исходном описании.
 */
export async function generateClarifyingQuestions(rawDescription) {
  await new Promise((resolve) => setTimeout(resolve, 600));

  const text = rawDescription.trim();

  return {
    questions: [
      "Кто является конечным пользователем решения?",
      "Какие данные уже доступны для работы над задачей?",
      "Какой конкретный результат и измеримые критерии успеха должны быть достигнуты?",
    ],

    extractedFields: {
      title:
        text.length > 35
          ? text.slice(0, 35) + "..."
          : text || "Новая бизнес-задача",

      context: text,
    },
  };
}

